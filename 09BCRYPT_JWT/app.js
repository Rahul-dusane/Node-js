//JWT :- To work with jwt we need to work install :- npm i jsonwebtoken
// It is a string
// Signed by the server
// Sent to the client (browser/mobile app)
// Returned back to server on every request (usually in headers)
// Used to identify the user
// It cannot be decrypted (unless using advanced encryption)
// It can only be verified 

// It has 3 parts:
// Header → algo + type
// Payload → data (like userId, email)
// Signature → proof that token is valid

app.get("/jwt",function(req,res){
    let token = jwt.sign({email: "xyz@eample.com"},"secret");    // this sign() method is used to generate the jwt token , as paremeters it will take the "userData/neccesary data and secrat key" to create the JWT token . and this token is send to browser by the server when user gets login .
    res.cookie("token",token);
    res.send("token has set in cookies . ");
});

app.get("/readJWT",function(req,res){
    let data =  jwt.verify(req.cookies.token,"secret");         // this verify() method is used to verify that the on the request of the logged in user that the token match that was generated by the server .
    console.log(data);
});

app.listen(3000);