const cookieParser = require('cookie-parser');
const express = require('express');
const app = express();
const bcrypt = require("bcrypt"); // it is used to HASHES the password so it cant be reversed(cant be decrypted) .
const jwt = require("jsonwebtoken");

app.use(express.json());
app.use(express.urlencoded({extended:true}));
app.use(cookieParser());

//to work with the bcrypt we need to install :- npm i bcrypt
app.get("/",function(req,res){
    bcrypt.genSalt(10,function(err,salt){               // the salt() method will add some extra random data to the password . to prevent attackers to guessing the password . it generate random string so 2 useer will never have the same password .
       bcrypt.hash("password",salt,function(err,hash){  // the hash() method will take you password and the randome salt and combine them both and create a irreversible hash(string) that cant be deycripted . we never store the real password in DB . we only store the hashed password . 
        console.log(hash);
       });
    });
});

